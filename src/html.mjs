// Self-contained HTML report generator for qnx-health-checker.
// Single file, inline CSS, no external assets.
import path from 'node:path';

function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const SEV_CLASS = { error: 'sev-error', warning: 'sev-warning', info: 'sev-info' };

export function renderHtml(report) {
  const name = esc(path.basename(report.project.replace(/\/$/, '')) || report.project);
  const verdictClass = report.verdict === 'Ready' ? 'verdict-ready'
    : report.verdict === 'Needs work' ? 'verdict-work' : 'verdict-not';
  const cats = ['build-system', 'buildfile', 'source', 'hygiene']
    .filter((c) => report.categories[c])
    .map((c) => {
      const cat = report.categories[c];
      const pct = Math.round((100 * cat.score) / cat.weight);
      return `<tr><td>${esc(c)}</td><td>${cat.score}/${cat.weight}</td>`
        + `<td><div class="bar"><div class="bar-fill" style="width:${pct}%"></div></div></td></tr>`;
    }).join('\n');
  const sorted = [...report.findings].sort((a, b) => {
    const rank = { error: 0, warning: 1, info: 2 };
    return rank[a.severity] - rank[b.severity] || a.id.localeCompare(b.id);
  });
  const rows = sorted.map((f) => {
    const where = f.file ? `${esc(f.file)}${f.line ? `:${f.line}` : ''}` : '(project)';
    const hint = f.hint ? `<div class="hint">Hint: ${esc(f.hint)}</div>` : '';
    return `<tr><td><span class="badge ${SEV_CLASS[f.severity]}">${f.severity.toUpperCase()}</span></td>`
      + `<td><strong>${esc(f.id)}</strong></td><td>${where}</td>`
      + `<td>${esc(f.message)}${hint}</td></tr>`;
  }).join('\n');
  const markers = report.markers.length > 0
    ? `<p><strong>QNX markers found:</strong> ${report.markers.map(esc).join(', ')}</p>`
    : '<p><strong>QNX markers found:</strong> none</p>';

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>QNX Health Check — ${name}</title>
<style>
body { font-family: system-ui, -apple-system, "Segoe UI", sans-serif; margin: 2rem auto; max-width: 900px; padding: 0 1rem; color: #1a1a1a; }
h1 { font-size: 1.6rem; margin-bottom: 0.2rem; }
.meta { color: #666; font-size: 0.9rem; }
.score { display: flex; align-items: center; gap: 1rem; margin: 1.2rem 0; }
.score-num { font-size: 2.6rem; font-weight: 700; }
.badge { display: inline-block; padding: 0.15rem 0.5rem; border-radius: 4px; font-size: 0.8rem; font-weight: 600; color: #fff; }
.verdict-ready { background: #1a7f37; color: #fff; padding: 0.3rem 0.8rem; border-radius: 4px; font-weight: 700; }
.verdict-work { background: #b25e09; color: #fff; padding: 0.3rem 0.8rem; border-radius: 4px; font-weight: 700; }
.verdict-not { background: #b3261e; color: #fff; padding: 0.3rem 0.8rem; border-radius: 4px; font-weight: 700; }
.sev-error { background: #b3261e; }
.sev-warning { background: #b25e09; }
.sev-info { background: #0969da; }
table { border-collapse: collapse; width: 100%; margin: 1rem 0; }
th, td { border: 1px solid #ddd; padding: 0.5rem 0.7rem; text-align: left; vertical-align: top; }
th { background: #f2f2f2; }
.bar { background: #eee; height: 12px; border-radius: 6px; min-width: 120px; }
.bar-fill { background: #1a7f37; height: 12px; border-radius: 6px; }
.hint { color: #555; font-size: 0.85rem; margin-top: 0.3rem; white-space: pre-wrap; }
footer { color: #888; font-size: 0.8rem; margin-top: 2rem; }
</style>
</head>
<body>
<h1>QNX Health Check — ${name}</h1>
<p class="meta">Directory: ${esc(report.project)} &middot; Files scanned: ${report.filesScanned} &middot; Generated by qnx-health-checker 0.1.0 (QNX SDP 8.0 rules)</p>
<div class="score">
  <div class="score-num">${report.score}<span style="font-size:1.2rem;color:#666">/100</span></div>
  <div><span class="${verdictClass}">${esc(report.verdict)}</span></div>
</div>
<h2>Category breakdown</h2>
<table><tr><th>Category</th><th>Score</th><th></th></tr>
${cats}
</table>
<p>${report.counts.total} findings — ${report.counts.errors} errors, ${report.counts.warnings} warnings, ${report.counts.infos} info.</p>
${markers}
<h2>Findings</h2>
<table><tr><th>Severity</th><th>Rule</th><th>Location</th><th>Detail</th></tr>
${rows || '<tr><td colspan="4">No findings — clean bill of health.</td></tr>'}
</table>
<footer>qnx-health-checker — static analysis for QNX 8.0 projects. Validates against QNX SDP 8.0 (qcc / GCC 12), targets QEMU x86_64 and aarch64. Not affiliated with BlackBerry QNX.</footer>
</body>
</html>
`;
}
